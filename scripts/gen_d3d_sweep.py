"""Generate src/d3d_sweep.gen.cpp: a call counter on every guest function in
the XDK D3D library range that is not already hooked elsewhere.

The sweep build (-DWWE_D3D_SWEEP=ON) reports the busiest functions from the
Present hook, to find the draw entry points this game uses.
Usage: python scripts/gen_d3d_sweep.py [lo] [hi] [extra_list]
extra_list: a file of further hex addresses to hook (e.g. analysis/d3d-callers.txt,
the game functions that call into the library).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
lo = int(sys.argv[1], 16) if len(sys.argv) > 1 else 0x82DA7AA0
hi = int(sys.argv[2], 16) if len(sys.argv) > 2 else 0x82DCECA0
init = (ROOT / "generated/default/wweallstars_init.cpp").read_text(errors="replace")
functions = sorted({int(a, 16) for a in re.findall(r"\{ (0x8[0-9A-F]{7}), sub_[0-9A-F]+ \}", init)})
hooked = set()
for source in (ROOT / "src").rglob("*.cpp"):
    if source.name != "d3d_sweep.gen.cpp":
        hooked |= {int(a, 16) for a in re.findall(r"REX_HOOK_RAW\(sub_([0-9A-F]{8})\)|HOOK\(([0-9A-F]{8})", source.read_text()) for a in a if a}
extra = set()
if len(sys.argv) > 3:
    extra = {int(line, 16) for line in Path(sys.argv[3]).read_text().split() if line}
targets = [a for a in functions if (lo <= a < hi or a in extra) and a not in hooked]
lines = [
    "// Generated by scripts/gen_d3d_sweep.py. Do not edit.",
    '#include "generated/default/wweallstars_pch.h"',
    "#include <rex/hook.h>",
    '#include "d3d_sweep.h"',
    "",
    "namespace wwe::sweep {",
    f"const uint32_t kAddresses[kCount] = {{{', '.join(f'0x{a:08X}' for a in targets)}}};",
    "}  // namespace wwe::sweep",
    "",
]
for index, address in enumerate(targets):
    lines += [
        f"DECLARE_REX_FUNC(sub_{address:08X});",
        f"REX_HOOK_RAW(sub_{address:08X}) {{ const auto mark = wwe::sweep::Enter({index}, base); __imp__sub_{address:08X}(ctx, base); wwe::sweep::Exit({index}, base, mark); }}",
    ]
(ROOT / "src/d3d_sweep.gen.cpp").write_text("\n".join(lines) + "\n")
(ROOT / "src/d3d_sweep_count.h").write_text(f"// Generated by scripts/gen_d3d_sweep.py.\n#pragma once\nnamespace wwe::sweep {{ inline constexpr int kCount = {len(targets)}; }}\n")
print(f"{len(targets)} sweep hooks")
